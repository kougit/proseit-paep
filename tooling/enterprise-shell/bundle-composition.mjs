#!/usr/bin/env node
/**
 * Bundle-composition check for DDR-IB3-07 (PO/SA, 2026-10-07 §5): what the reference-app initial bundle is made of.
 * Builds the production configuration once more with source maps into a temporary directory (the code is the same
 * configuration; see C7), attributes every byte of the initial files to its source,
 * and checks:
 *   C1 no UI-lab, tooling, analytics, offline, Frappe SDK or domain-package source
 *   C2 no spec or test-double source (`*.spec.ts`, `lib/testing/`)
 *   C3 third-party code only from @angular/*, rxjs and tslib (no new dependency)
 *   C4 no PAEP source included twice (for example through a deep or node_modules path besides the workspace path)
 *   C5 no component selector defined twice (no duplicate primitive), and one popover positioning implementation
 *   C6 the production configuration keeps optimisation and AOT on, no source maps, no named chunks
 *   C7 this build has the production build's initial files (same roles) and its raw total is within 1 % (a source-mapped
 *      build mangles some identifiers differently, so the bytes are not identical; the delta is reported)
 *   node tooling/enterprise-shell/bundle-composition.mjs [--json <file>]
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { DIST, measureInitial } from './shell-qa.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const { SourceMapConsumer } = createRequire(import.meta.url)(path.join(ROOT, 'node_modules/source-map-js'));
const args = process.argv.slice(2);
const jsonOut = args.includes('--json') ? path.resolve(args[args.indexOf('--json') + 1]) : null;

const out = fs.mkdtempSync(path.join(os.tmpdir(), 'paep-bundle-composition-'));
const results = [];
const add = (id, name, problems, detail) => results.push({ id, name, problems, detail });
try {
  const ng = path.join(ROOT, 'node_modules/@angular/cli/bin/ng.js');
  const b = spawnSync(process.execPath, [ng, 'build', 'reference-app', '--configuration', 'production', '--source-map', '--output-path', out], { cwd: ROOT, encoding: 'utf8' });
  if (b.status !== 0) throw new Error(`source-mapped build failed: ${(b.stdout + b.stderr).slice(-800)}`);
  const dir = path.join(out, 'browser');
  const { files } = measureInitial(dir);

  // Attribute generated bytes to sources.
  const bySource = new Map();
  for (const f of files.filter((x) => x.endsWith('.js'))) {
    const code = fs.readFileSync(path.join(dir, f), 'utf8');
    const lines = code.split('\n');
    const map = new SourceMapConsumer(JSON.parse(fs.readFileSync(path.join(dir, `${f}.map`), 'utf8')));
    let prev = null;
    map.eachMapping((m) => {
      if (prev) {
        const len = prev.line === m.generatedLine ? m.generatedColumn - prev.col : lines[prev.line - 1].length - prev.col;
        bySource.set(prev.src, (bySource.get(prev.src) ?? 0) + Math.max(0, len));
      }
      prev = { line: m.generatedLine, col: m.generatedColumn, src: m.source ?? '(unmapped)' };
    });
  }
  const norm = (s) => s.replace(/^(\.\.\/)+/, '').replace(/^webpack:\/\/\//, '');
  const sources = [...bySource.keys()].filter((s) => s !== '(unmapped)').map(norm);
  const group = (s) => (s.includes('node_modules/') ? s.split('node_modules/').pop().split('/').slice(0, s.split('node_modules/').pop().startsWith('@') ? 2 : 1).join('/') : s.split('/').slice(0, 2).join('/'));
  const groups = {};
  for (const [s, n] of bySource) groups[group(norm(s))] = (groups[group(norm(s))] ?? 0) + n;
  const composition = Object.entries(groups).sort((x, y) => y[1] - x[1]).map(([g, n]) => ({ source: g, kB: Number((n / 1000).toFixed(1)) }));

  add('C1', 'No UI-lab, tooling, analytics, offline, Frappe SDK or domain-package source in the initial bundle',
    sources.filter((s) => /^(apps\/ui-lab|tooling)\/|^packages\/(analytics|offline|frappe-sdk|domain-[a-z]+)\//.test(s) || /@proseit\/(paep-analytics|paep-offline|frappe-sdk|paep-domain-)/.test(s)));
  add('C2', 'No spec or test-double source', sources.filter((s) => /\.spec\.ts$|\/lib\/testing\//.test(s)));
  const thirdParty = [...new Set(sources.filter((s) => s.includes('node_modules/')).map(group))];
  add('C3', 'Third-party code only from @angular/*, rxjs and tslib', thirdParty.filter((g) => !/^(@angular\/[a-z-]+|rxjs|tslib)$/.test(g)), thirdParty.join(', '));
  const paep = sources.filter((s) => !s.includes('node_modules/') || s.includes('@proseit/'));
  const key = (s) => s.replace(/^.*node_modules\/@proseit\/(?:paep-)?([a-z-]+)\//, 'packages/$1/');
  const seen = new Map();
  for (const s of paep) seen.set(key(s), [...(seen.get(key(s)) ?? []), s]);
  add('C4', 'No PAEP source included twice (deep, node_modules or workspace paths)', [...seen.values()].filter((v) => v.length > 1).map((v) => v.join(' + ')));

  const code = files.filter((x) => x.endsWith('.js')).map((f) => fs.readFileSync(path.join(dir, f), 'utf8')).join('\n');
  const selectors = [...code.matchAll(/selectors:(\[\[[^\]]*\](?:,\[[^\]]*\])*\])/g)].map((m) => m[1]);
  const dup = [...new Set(selectors.filter((x, i) => selectors.indexOf(x) !== i))];
  const positioning = sources.filter((s) => /^packages\/[a-z-]+\/src\/lib\/.*\.ts$/.test(s) && /\bdata-placement\b/.test(fs.readFileSync(path.join(ROOT, s), 'utf8')));
  add('C5', 'No component selector defined twice; one popover positioning implementation',
    [...dup.map((x) => `selector ${x} defined ${selectors.filter((y) => y === x).length} times`), ...(positioning.length === 1 && positioning[0] === 'packages/components/src/lib/popover/popover.ts' ? [] : [`positioning sources: ${positioning.join(', ') || 'none'}`])],
    `${selectors.length} component definitions; positioning in ${positioning.join(', ')}`);

  const prod = JSON.parse(fs.readFileSync(path.join(ROOT, 'angular.json'), 'utf8')).projects['reference-app'].architect.build;
  const cfg = { ...prod.options, ...prod.configurations.production };
  const c6 = [];
  if (cfg.optimization === false) c6.push('optimization is off');
  if (cfg.aot === false) c6.push('AOT is off');
  if (cfg.sourceMap) c6.push('source maps are on');
  if (cfg.namedChunks) c6.push('named chunks are on');
  add('C6', 'Production configuration: optimisation and AOT on, no source maps, no named chunks', c6, `optimization=${cfg.optimization ?? 'default (on)'}, aot=${cfg.aot ?? 'default (on)'}, sourceMap=${cfg.sourceMap ?? false}, namedChunks=${cfg.namedChunks ?? false}`);

  const role = (f) => f.replace(/-[A-Za-z0-9_-]{8}\.(js|css)$/, '.$1');
  const prodFiles = fs.existsSync(path.join(DIST, 'index.html')) ? measureInitial(DIST).files : [];
  const c7 = [];
  if (!prodFiles.length) c7.push(`${DIST} has no production build: run npm run build:reference-app first`);
  else if (prodFiles.map(role).join() !== files.map(role).join()) c7.push(`initial files differ: ${prodFiles.join(', ')} vs ${files.join(', ')}`);
  const prodRaw = prodFiles.length ? measureInitial(DIST).raw : 0;
  const mappedRaw = measureInitial(dir).raw;
  if (prodRaw && Math.abs(mappedRaw - prodRaw) > prodRaw / 100) c7.push(`raw ${mappedRaw} bytes vs production ${prodRaw} bytes: more than 1 % apart`);
  add('C7', 'This build has the production initial files and a raw total within 1 % of it', c7, `production ${prodRaw} bytes, source-mapped ${mappedRaw} bytes`);

  const m = measureInitial(DIST);
  const failed = results.filter((r) => r.problems.length);
  for (const r of results) {
    console.log(`${r.problems.length ? 'FAIL' : 'PASS'} ${r.id} ${r.name}${r.detail ? ` — ${r.detail}` : ''}`);
    for (const x of r.problems.slice(0, 20)) console.log(`     ${x}`);
  }
  console.log(`\nComposition of the initial bundle (${m.raw} bytes raw, ${m.transfer} bytes transfer):`);
  for (const c of composition.slice(0, 25)) console.log(`  ${String(c.kB).padStart(6)} kB  ${c.source}`);
  if (jsonOut) fs.writeFileSync(jsonOut, JSON.stringify({ ok: !failed.length, raw: m.raw, transfer: m.transfer, files: m.files, results, composition }, null, 2) + '\n');
  console.log(`\nPAEP reference-app bundle composition: ${failed.length ? 'FAIL' : 'PASS'} (${results.length - failed.length}/${results.length})`);
  process.exitCode = failed.length ? 1 : 0;
} finally {
  fs.rmSync(out, { recursive: true, force: true });
}
